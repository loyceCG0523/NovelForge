def build_generation_quality_contract(chapter_index: int) -> dict[str, Any]:
    """给正文模型的结构化质量门槛。"""
    return {
        "priority": "仅次于人物、世界和剧情硬事实；与字数要求同为交付门槛。",
        "rules": [
            {"dimension": item["key"], "requirement": item["generation_rule"]}
            for item in QUALITY_DIMENSIONS
        ],
        "storytelling_craft": build_storytelling_craft_contract(),
        "first_chapter_extra": (
            [
                "首章不是背景说明书：前10%必须发生具体扰动，前25%必须出现一次计划受阻、判断反转或更糟的新信息；背景只随行动和冲突露出。",
                "首章至少安排4个分散的类型化回报；喜剧作品优先做到5—7个因果型喜剧节拍，不能把网络热梗当笑点指标。",
                "核心对手戏人物应尽早以本人、声音、消息或直接行动进入；首章结束前必须让双方目标发生第一次有效碰撞。",
                "首章可以推进快，但每次重大关系跃迁都要有可信的因果台阶。",
                "最后2—4段必须抛出会立刻改变下一步行动的新信息、选择、威胁或关系反转，让读者能说出‘下一章我必须知道什么’。",
            ]
            if chapter_index == 1
            else []
        ),
        "silent_preflight": "输出前逐项核对 rules；只修正文，不输出检查过程。",
    }


